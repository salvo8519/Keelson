"""Build the multilingual documentation (English source, one edition per i18n/<lang>.yaml).

Zensical builds one language per site, so each language is a separate site sharing the same
assets: English at the site root, other languages under /<lang>/, linked by the language
selector. One copy serves Keelson and every generated project (DOCS_ROOT selects the root).

    python scripts/docs.py build           # every site into site/ and site/<lang>/ (strict)
    python scripts/docs.py serve --lang it # live preview of one language
    python scripts/docs.py prepare         # copy shared assets, generate zensical.<lang>.toml
"""

from __future__ import annotations

import argparse
import copy
import fnmatch
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import Any

import tomli_w
import yaml

ROOT = Path(os.environ.get("DOCS_ROOT") or Path(__file__).resolve().parents[1]).resolve()
DOCS = ROOT / "docs"
SHARED = DOCS / "_shared"
EDITIONS = sorted(p.stem for p in (ROOT / "i18n").glob("*.yaml") if p.stem != "glossary")
LANGS = ["en", *EDITIONS]


def copy_shared() -> None:
    for lang in LANGS:
        for item in SHARED.iterdir():
            target = DOCS / lang / item.name
            if target.exists():
                shutil.rmtree(target) if target.is_dir() else target.unlink()
            if item.is_dir():
                shutil.copytree(item, target)
            else:
                shutil.copy2(item, target)


def translate_nav(nav: list[Any], cfg: dict[str, Any], en_site: str, lang: str) -> list[Any]:
    out: list[Any] = []
    for entry in nav:
        for title, value in entry.items():
            label = cfg["sections"].get(title, title)
            if isinstance(value, list):
                children = translate_nav(value, cfg, en_site, lang)
                if children:
                    out.append({label: children})
            else:
                page = value
                if any(fnmatch.fnmatch(page, p) for p in cfg["english_only"]):
                    url = en_site + page.removesuffix(".md") + "/"
                    suffix = cfg.get("english_only_suffix", "(English)")
                    out.append({f"{h1(DOCS / 'en' / page)} {suffix}": url})
                elif (DOCS / lang / page).exists():
                    out.append({label: page})
    return out


def h1(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem.replace("-", " ").capitalize()


def flatten(nav: list[Any]) -> list[Any]:
    """Zensical nav entries: plain page paths where possible."""
    out: list[Any] = []
    for entry in nav:
        for title, value in entry.items():
            if isinstance(value, list):
                out.append({title: flatten(value)})
            elif title in ("Home",) or value.startswith("http"):
                out.append({title: value})
            else:
                out.append(value)
    return out


def edition_config(lang: str) -> None:
    """zensical.<lang>.toml: the English configuration with the edition's texts and nav."""
    base = tomllib.loads((ROOT / "zensical.toml").read_text(encoding="utf-8"))
    cfg = yaml.safe_load((ROOT / "i18n" / f"{lang}.yaml").read_text(encoding="utf-8"))
    edition = copy.deepcopy(base)
    p = edition["project"]
    en_site = base["project"]["site_url"]
    p["site_url"] = en_site + f"{lang}/"
    p["site_description"] = cfg["site_description"]
    if "copyright" in cfg:
        p["copyright"] = cfg["copyright"]
    p["docs_dir"] = f"docs/{lang}"
    p["site_dir"] = f"site/{lang}"
    if "edit_uri" in p:
        p["edit_uri"] = p["edit_uri"].replace("docs/en/", f"docs/{lang}/")
    p["theme"]["language"] = lang
    nav = flatten(translate_nav(_normalise(base["project"]["nav"]), cfg, en_site, lang))
    del p["nav"]
    header = (
        f"# GENERATED by scripts/docs.py from zensical.toml and i18n/{lang}.yaml. Do not edit.\n\n"
    )
    body = tomli_w.dumps(edition)
    marker = "\n[project."
    cut = body.index(marker)
    nav_toml = "nav = " + toml_inline(nav, 0) + "\n"
    (ROOT / f"zensical.{lang}.toml").write_text(
        header + body[:cut] + "\n" + nav_toml + body[cut:], encoding="utf-8"
    )


def toml_inline(value: Any, indent: int) -> str:
    """Serialise the nav as TOML inline arrays/tables (mixed arrays allowed by TOML 1.0)."""
    pad = "  " * (indent + 1)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, dict):
        ((k, v),) = value.items()
        return "{ " + toml_inline(k, indent) + " = " + toml_inline(v, indent) + " }"
    items = ",\n".join(pad + toml_inline(v, indent + 1) for v in value)
    return "[\n" + items + ",\n" + "  " * indent + "]"


def _normalise(nav: list[Any]) -> list[Any]:
    out: list[Any] = []
    for entry in nav:
        if isinstance(entry, str):
            out.append({entry: entry})
        else:
            for title, value in entry.items():
                out.append({title: _normalise(value) if isinstance(value, list) else value})
    return out


def page_list(nav: list[Any]) -> list[str]:
    pages: list[str] = []
    for entry in nav:
        if isinstance(entry, str):
            pages.append(entry)
        else:
            for value in entry.values():
                pages += page_list(value) if isinstance(value, list) else [value]
    return pages


def publish_openapi() -> None:
    """Publish the API contract with the site, at /openapi.json, when the project has one."""
    document = ROOT / "openapi" / "openapi.json"
    if document.exists():
        shutil.copy2(document, ROOT / "site" / "openapi.json")


def llms_txt() -> None:
    """Agent-readable context (llmstxt.org): an index and the full English documentation."""
    base = tomllib.loads((ROOT / "zensical.toml").read_text(encoding="utf-8"))["project"]
    site = base["site_url"]
    pages = [p for p in page_list(base["nav"]) if not p.startswith("http")]
    index = [
        f"# {base['site_name']}",
        "",
        f"> {base['site_description']}",
        "",
        "Code and identifiers are English."
        + "".join(f" Edition {lang}: {site}{lang}/" for lang in EDITIONS),
        "",
        "## Documentation",
        "",
    ]
    full = [f"# {base['site_name']} — full documentation", ""]
    for page in pages:
        path = DOCS / "en" / page
        text = path.read_text(encoding="utf-8")
        if text.startswith("--8<--"):
            text = (ROOT / text.split('"')[1]).read_text(encoding="utf-8")
        text = re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.DOTALL)
        url = site + ("" if page == "index.md" else page.removesuffix(".md") + "/")
        index.append(f"- [{h1(path)}]({url})")
        full += [f"<!-- source: {url} -->", text.strip(), ""]
    for extra in ("CHANGELOG.md", "RELEASE_NOTES.md"):
        if not (ROOT / extra).exists():
            continue
        full += [f"<!-- source: {extra} -->", (ROOT / extra).read_text(encoding="utf-8"), ""]
    (ROOT / "site" / "llms.txt").write_text("\n".join(index) + "\n", encoding="utf-8")
    (ROOT / "site" / "llms-full.txt").write_text("\n".join(full), encoding="utf-8")


GENERATED = ROOT / ".generated" / "docs"


UNRELEASED_TITLE = "## Keelson Unreleased"


def undated_draft(draft: str) -> str:
    """Drop the date from the title of the unreleased section.

    towncrier dates every section it builds; for the draft that date is the day the site was
    built, which readers would take for a release date. Released sections keep their date.
    """
    first, sep, rest = draft.partition("\n")
    if first.startswith(UNRELEASED_TITLE):
        return UNRELEASED_TITLE + sep + rest
    return draft


def current_notes() -> None:
    """Release notes and changelog as of now, for the site (never committed).

    RELEASE_NOTES.md and CHANGELOG.md in the repository are written at release time. The site
    shows them with the unreleased changes included, so that what users read is current:
    the draft section of the release notes comes from the fragments in changes/ (towncrier),
    the unreleased section of the changelog from the commits since the last tag (git-cliff).
    """
    GENERATED.mkdir(parents=True, exist_ok=True)
    draft = subprocess.run(
        ["towncrier", "build", "--draft", "--version", "Unreleased"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
        encoding="utf-8",
    ).stdout.strip()
    notes = (ROOT / "RELEASE_NOTES.md").read_text(encoding="utf-8")
    marker = "<!-- release notes start -->\n"
    if marker not in notes:
        sys.exit("RELEASE_NOTES.md: release notes marker missing")
    if "No significant changes" in draft or not draft:
        draft = UNRELEASED_TITLE + "\n\nNo user-facing changes since the last release."
    draft = undated_draft(draft)
    head, tail = notes.split(marker, 1)
    (GENERATED / "RELEASE_NOTES.md").write_text(
        head + marker + "\n" + draft + "\n\n" + tail.lstrip("\n"), encoding="utf-8"
    )
    result = subprocess.run(
        ["git-cliff"], cwd=ROOT, capture_output=True, text=True, check=False, encoding="utf-8"
    )
    # A repository without commits yet has no changelog to render.
    changelog = (
        result.stdout
        if result.returncode == 0 and result.stdout.strip()
        else ((ROOT / "CHANGELOG.md").read_text(encoding="utf-8"))
    )
    (GENERATED / "CHANGELOG.md").write_text(changelog, encoding="utf-8")


def prepare() -> None:
    if SHARED.is_dir():
        copy_shared()
    for lang in EDITIONS:
        edition_config(lang)
    # Release notes with the unreleased changes, where the repository keeps them (towncrier).
    if (ROOT / "RELEASE_NOTES.md").exists() and (ROOT / "changes").is_dir():
        current_notes()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["prepare", "build", "serve"])
    parser.add_argument("--lang", choices=LANGS, default="en")
    args = parser.parse_args()
    prepare()
    configs = {"en": "zensical.toml"} | {lang: f"zensical.{lang}.toml" for lang in EDITIONS}
    if args.command == "build":
        shutil.rmtree(ROOT / "site", ignore_errors=True)
        for lang in LANGS:
            subprocess.run(
                ["zensical", "build", "--strict", "-f", configs[lang]], cwd=ROOT, check=True
            )
        llms_txt()
        publish_openapi()
    elif args.command == "serve":
        subprocess.run(["zensical", "serve", "-f", configs[args.lang]], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
