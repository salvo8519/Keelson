"""Write the skills lock of this repository from the one in the template.

The pins of the component skills live in one place, ``template/skills.lock.toml.jinja``.
Generated projects render it with their answers; this repository renders it with every
component enabled and git sources only (``keelstone_dev``), so that agents working on the
template get the same skills, at the same commits, as the projects it generates.

    python scripts/skills_lock.py           # write skills.lock.toml
    python scripts/skills_lock.py --check   # exit 1 if skills.lock.toml is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "skills.lock.toml.jinja"
TARGET = ROOT / "skills.lock.toml"

# Every component the template can generate, so the repository covers all of them.
CONTEXT = {
    "keelstone_dev": True,
    "use_pydantic_ai": True,
    "use_pydantic_deep": False,
    "use_langchain": False,
    "use_langgraph": True,
    "use_deepagents": False,
    "enable_logfire": True,
    "use_qdrant": True,
    "web_frontend": "react",
}

HEADER = (
    "# GENERATED by scripts/skills_lock.py from template/skills.lock.toml.jinja. Do not edit.\n"
)


def render() -> str:
    env = Environment(
        loader=FileSystemLoader(ROOT / "template"),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
    )
    return HEADER + env.get_template(SOURCE).render(**CONTEXT)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("skills.lock.toml is stale. Run: python scripts/skills_lock.py", file=sys.stderr)
            return 1
        print("skills.lock.toml matches the template.")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
